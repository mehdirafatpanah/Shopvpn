def item_body(item_key: str):
    """Detailed guide text of one panel item, or None when there is none."""
    return ITEM_HELP.get(item_key) or _gateway_help(item_key)


def _build_index() -> None:
    if _cb_index:
        return
    for cat_key, _label, item_keys in kb.ADMIN_PANEL_CATEGORIES:
        for item_key in item_keys:
            _label_text, callback_data = kb._admin_item_label_and_cb(item_key)
            _cb_index.setdefault(callback_data, (cat_key, item_key))


def track(admin_id: int, callback_data: str) -> None:
    """Remember the top-level section the admin just opened."""
    data = callback_data or ""
    if data in ("adm_back_panel", "adm_exit_panel"):
        _sections.pop(admin_id, None)
        return
    if data.startswith("adm_cat:"):
        cat_key = data.split(":", 1)[1]
        _sections[admin_id] = ({"cb": data, "cat": cat_key, "item": None}, time.monotonic())
        return
    _build_index()
    hit = _cb_index.get(data)
    if hit:
        _sections[admin_id] = ({"cb": data, "cat": hit[0], "item": hit[1]}, time.monotonic())


def current(admin_id: int):
    entry = _sections.get(admin_id)
    if not entry or time.monotonic() - entry[1] > _TTL:
        _sections.pop(admin_id, None)
        return None
    return entry[0]


def attach_button(admin_id: int, reply_markup):
    """Append the help button row to an admin screen when a section is active."""
    if not isinstance(reply_markup, InlineKeyboardMarkup) or not current(admin_id):
        return reply_markup
    for row in reply_markup.inline_keyboard:
        for button in row:
            if button.callback_data in (HELP_CB, "adm_exit_panel"):
                return reply_markup
    rows = [list(row) for row in reply_markup.inline_keyboard]
    rows.append([InlineKeyboardButton(text="📖 راهنمای این بخش", callback_data=HELP_CB)])
    return InlineKeyboardMarkup(inline_keyboard=rows)


def _button_lines(cat_key: str, db, is_main_bot: bool) -> str:
    for key, _label, item_keys in kb.ADMIN_PANEL_CATEGORIES:
        if key != cat_key:
            continue
        lines = []
        for item_key in item_keys:
            if not kb._is_item_visible(db, item_key, is_main_bot):
                continue
            label, _cb = kb._admin_item_label_and_cb(item_key)
            lines.append(f"• {label}")
        return "\n".join(lines)
    return ""


def guide_text(section: dict, db, is_main_bot: bool) -> str:
    cat_key = section["cat"]
    cat_title = kb.admin_category_label(cat_key)
    item_key = section.get("item")
    if item_key:
        label, _cb = kb._admin_item_label_and_cb(item_key)
        body = item_body(item_key)
        if body:
            return f"📖 راهنمای {label}\n\n{body}"
        return f"📖 راهنمای {label}\n\n{cat_title}\n{CATEGORY_HELP.get(cat_key, '')}"
    return (
        f"📖 راهنمای {cat_title}\n\n{CATEGORY_HELP.get(cat_key, '')}\n\n"
        f"دکمه‌های این دسته:\n{_button_lines(cat_key, db, is_main_bot)}\n\n"
        "داخل هر دکمه بزن و «📖 راهنمای این بخش» را انتخاب کن تا همان بخش را کامل توضیح بدهم."
    )


def _first_paragraph(text: str, limit: int = 260) -> str:
    head = text.split("\n\n", 1)[0].strip()
    return head if len(head) <= limit else head[:limit].rstrip() + "…"


def assistant_context(section: dict, db, is_main_bot: bool) -> str:
    """Full reference text handed to the admin assistant for the section being asked about."""
    cat_key = section["cat"]
    cat_title = kb.admin_category_label(cat_key)
    parts = [f"دسته‌ی فعلی پنل: {cat_title}", CATEGORY_HELP.get(cat_key, "")]
    item_key = section.get("item")
    if item_key:
        label, _cb = kb._admin_item_label_and_cb(item_key)
        parts.append(f"دکمه‌ای که ادمین الان باز کرده: {label}")
        parts.append(item_body(item_key) or "")
        siblings = _button_lines(cat_key, db, is_main_bot)
        if siblings:
            parts.append(f"دکمه‌های دیگر همین دسته:\n{siblings}")
        return "\n\n".join(p for p in parts if p)
    for key, _label, item_keys in kb.ADMIN_PANEL_CATEGORIES:
        if key != cat_key:
            continue
        for ik in item_keys:
            if not kb._is_item_visible(db, ik, is_main_bot):
                continue
            label, _cb = kb._admin_item_label_and_cb(ik)
            body = item_body(ik)
            parts.append(f"• {label}\n{_first_paragraph(body) if body else ''}".rstrip())
    return "\n\n".join(p for p in parts if p)


_GUIDE_CHARS = 1800
_DIGITS = str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789")
_STOP_WORDS = frozenset({
    "چطور", "چگونه", "کجا", "میشه", "می", "شه", "را", "رو", "از", "به", "در", "که", "این", "آن", "چی", "چه",
    "کنم", "کردن", "برای", "با", "و", "یا", "هست", "است", "بکنم", "بدم", "باید", "ها", "های", "میخوام", "خوام",
})


def _norm_text(text) -> str:
    return (
        str(text or "").translate(_DIGITS).replace("ي", "ی").replace("ك", "ک")
        .replace("\u200c", " ").lower().strip()
    )


def _query_words(query: str) -> list:
    words = []
    for raw in re.split(r"[\s،,.؟?!:؛()\-_/«»\"']+", _norm_text(query)):
        for suffix in ("های", "ها"):
            if raw.endswith(suffix) and len(raw) - len(suffix) >= 2:
                raw = raw[: -len(suffix)]
                break
        if len(raw) >= 2 and raw not in _STOP_WORDS:
            words.append(raw)
    return words


def panel_map(db, is_main_bot: bool) -> str:
    """One line per panel category listing the visible button labels."""
    lines = []
    for cat_key, _label, item_keys in kb.ADMIN_PANEL_CATEGORIES:
        labels = [
            kb._admin_item_label_and_cb(ik)[0]
            for ik in item_keys
            if kb._is_item_visible(db, ik, is_main_bot)
        ]
        if labels:
            lines.append(f"{kb.admin_category_label(cat_key)}: " + " | ".join(labels))
    return "\n".join(lines)


def search_guides(query: str, db, is_main_bot: bool, limit: int = 3) -> dict:
    """Best-matching panel guides (path + guide text) for a free-text topic."""
    words = _query_words(query)
    scored = []
    for cat_key, _label, item_keys in kb.ADMIN_PANEL_CATEGORIES:
        for item_key in item_keys:
            if not kb._is_item_visible(db, item_key, is_main_bot):
                continue
            label, _cb = kb._admin_item_label_and_cb(item_key)
            body = item_body(item_key) or ""
            label_n, body_n = _norm_text(label), _norm_text(body)
            score = sum((3 if w in label_n else 0) + min(body_n.count(w), 3) for w in words)
            if score:
                scored.append((score, cat_key, label, body))
    scored.sort(key=lambda row: -row[0])
    matches = [
        {
            "path": f"/admin ← {kb.admin_category_label(cat)} ← {label}",
            "guide": body[:_GUIDE_CHARS] or CATEGORY_HELP.get(cat, ""),
        }
        for _score, cat, label, body in scored[:limit]
    ]
    if not matches:
        return {"matches": [], "note": "راهنمای مرتبطی پیدا نشد؛ از نقشه‌ی پنل نزدیک‌ترین دکمه را معرفی کن و بگو در راهنما نیست."}
    return {"matches": matches}


